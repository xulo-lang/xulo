//! 生成解释器 FFI trampoline：按参数寄存器类（i64 / f32 / f64）× 参数个数
//! 0..=6 × 返回类（void / u8 / u16 / u32 / u64 / f32 / f64）穷举 `extern "C"`
//! fn 类型并 transmute 调用。实参统一以 i64 携带窄整类（x86-64 SysV 下
//! callee 只读低位），返回按宽度读取、符号扩展在调用侧按 AST 类型解释
//! （窄返回的高位未定义，必须按窄类型声明——见 ffi.rs 的 Wide 语义）。
//!
//! 代码量 = 3^k × 7 个调用点（k=6 时 7651 个）。单个巨型 match 在
//! release `-O3` 下会把 rustc/LLVM 打爆（SIGKILL/OOM），所以按
//! **(参数个数, 返回类)** 切成 49 个独立函数——最大片 729 个 arm，
//! 逐函数处理，峰值内存与最大片成正比而非与总量成正比。
//!
//! 输出 `$OUT_DIR/ffi_trampolines.rs`，由 `interpreter::ffi` `include!`。
//! Edition 2024：生成的是普通安全 fn，transmute 与 C 调用各自包 `unsafe`。
use std::env;
use std::fs;
use std::path::PathBuf;

const MAX_PARAMS: usize = 6;

fn param_ty(class: u8) -> &'static str {
    match class {
        0 => "i64",
        1 => "f32",
        _ => "f64",
    }
}

fn arg_fn(class: u8) -> &'static str {
    match class {
        0 => "arg_i64",
        1 => "arg_f32",
        _ => "arg_f64",
    }
}

fn ret_ty(ret: u8) -> &'static str {
    match ret {
        0 => "",
        1 => "-> u8",
        2 => "-> u16",
        3 => "-> u32",
        4 => "-> u64",
        5 => "-> f32",
        _ => "-> f64",
    }
}

fn wrap(ret: u8) -> &'static str {
    match ret {
        0 => "FfiRet::Void",
        1..=4 => "FfiRet::Wide(v as u64)",
        5 => "FfiRet::F32(v)",
        _ => "FfiRet::F64(v)",
    }
}

/// 按字典序遍历 {0,1,2}^k 的所有组合
fn class_product(k: usize) -> Vec<Vec<u8>> {
    let mut out = vec![Vec::new()];
    for _ in 0..k {
        let mut next = Vec::with_capacity(out.len() * 3);
        for prefix in &out {
            for c in 0..3u8 {
                let mut combo = prefix.clone();
                combo.push(c);
                next.push(combo);
            }
        }
        out = next;
    }
    out
}

/// 一个 (k, ret) 片：`match params { [类…] => 调用, … }`，ret 固定。
fn emit_shard(s: &mut String, k: usize, ret: u8) {
    s.push_str("#[allow(clippy::all, unused_variables)]\n");
    s.push_str(&format!(
        "pub(crate) fn k{k}_r{ret}(params: &[u8], addr: usize, args: &[FfiArg]) -> Option<FfiRet> {{\n"
    ));
    s.push_str("    match params {\n");
    for combo in class_product(k) {
        let pat = combo
            .iter()
            .map(|c| c.to_string())
            .collect::<Vec<_>>()
            .join(", ");
        let tys = combo
            .iter()
            .map(|c| param_ty(*c))
            .collect::<Vec<_>>()
            .join(", ");
        let bindings = (0..k)
            .map(|i| format!("let a{i} = {}(args, {i})?;", arg_fn(combo[i])))
            .collect::<Vec<_>>()
            .join("");
        let call_args = (0..k)
            .map(|i| format!("a{i}"))
            .collect::<Vec<_>>()
            .join(", ");
        let (ret_decl, body) = if ret == 0 {
            (String::new(), format!("f({call_args}); FfiRet::Void"))
        } else {
            (
                format!(" {}", ret_ty(ret)),
                format!("let v = f({call_args}); {}", wrap(ret)),
            )
        };
        s.push_str(&format!(
            "        [{pat}] => {{\n\
             \x20           {bindings}\n\
             \x20           Some(unsafe {{\n\
             \x20               let f: extern \"C\" fn({tys}){ret_decl} = std::mem::transmute(addr);\n\
             \x20               {body}\n\
             \x20           }})\n\
             \x20       }}\n",
        ));
    }
    s.push_str("        _ => None,\n");
    s.push_str("    }\n");
    s.push_str("}\n\n");
}

fn main() {
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    let mut s = String::with_capacity(1 << 20);
    s.push_str("// @generated by build.rs — do not edit.\n");
    s.push_str("#[allow(clippy::all, unused_variables, unused_assignments)]\n");
    s.push_str("pub(crate) fn invoke(\n");
    s.push_str("    params: &[u8],\n");
    s.push_str("    ret: u8,\n");
    s.push_str("    addr: usize,\n");
    s.push_str("    args: &[FfiArg],\n");
    s.push_str(") -> Option<FfiRet> {\n");
    s.push_str("    // 分发到 (参数个数, 返回类) 片；片内精确匹配参数类序列\n");
    s.push_str("    match (params.len(), ret) {\n");
    for k in 0..=MAX_PARAMS {
        for r in 0..7u8 {
            s.push_str(&format!(
                "        ({k}, {r}) => k{k}_r{r}(params, addr, args),\n"
            ));
        }
    }
    s.push_str("        _ => None,\n");
    s.push_str("    }\n");
    s.push_str("}\n\n");
    for k in 0..=MAX_PARAMS {
        for r in 0..7u8 {
            emit_shard(&mut s, k, r);
        }
    }
    fs::write(out_dir.join("ffi_trampolines.rs"), s).expect("write ffi trampolines");
}
